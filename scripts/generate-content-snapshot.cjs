const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const { spawnSync } = require("node:child_process");
const { verifyContent } = require("./content-verify.cjs");

const appRoot = path.resolve(__dirname, "..");
const contentRoot = path.resolve(process.env.BLOG_CONTENT_ROOT || path.join(appRoot, ".content"));
const outputPath = path.join(appRoot, "src", "generated", "contentSnapshot.ts");

function sha256(value) {
  return crypto.createHash("sha256").update(value).digest("hex");
}

function walkMarkdown(directory, prefix) {
  if (!fs.existsSync(directory)) return [];
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const absolute = path.join(directory, entry.name);
    const relative = path.join(prefix, entry.name).replaceAll(path.sep, "/");
    if (entry.isSymbolicLink()) throw new Error(`内容仓库不允许符号链接：${relative}`);
    if (entry.isDirectory()) return walkMarkdown(absolute, relative);
    if (!entry.isFile() || !entry.name.endsWith(".md")) return [];
    return [{ path: relative, content: fs.readFileSync(absolute, "utf8") }];
  });
}

function readOptionalJson(relative) {
  const absolute = path.join(contentRoot, relative);
  if (!fs.existsSync(absolute)) return null;
  if (fs.statSync(absolute).size === 0) return null;
  try {
    return JSON.parse(fs.readFileSync(absolute, "utf8"));
  } catch (error) {
    throw new Error(`${relative} 不是有效 JSON：${error.message}`);
  }
}

if (!fs.existsSync(contentRoot) || !fs.statSync(contentRoot).isDirectory()) {
  throw new Error(`内容根目录不存在：${contentRoot}`);
}

const posts = walkMarkdown(path.join(contentRoot, "posts"), "posts");
const snippets = walkMarkdown(path.join(contentRoot, "snippets"), "snippets");
verifyContent(contentRoot);
const pin = JSON.parse(fs.readFileSync(path.join(appRoot, "release.json"), "utf8"));
const releaseId = process.env.CONTENT_SHA || pin.contentSha;
const checkout = spawnSync("git", ["-C", contentRoot, "rev-parse", "HEAD"], { encoding: "utf8" });
if (checkout.status !== 0 || checkout.stdout.trim() !== releaseId) throw new Error("Build content does not match the release commit pin");
const manifest = readOptionalJson("content-manifest.json");
const snapshot = {
  generated: true,
  frameworkSha: spawnSync("git", ["rev-parse", "HEAD"], { cwd: appRoot, encoding: "utf8" }).stdout.trim(),
  releaseId,
  snapshotDigest: typeof manifest?.snapshotDigest === "string" ? manifest.snapshotDigest : "dev",
  posts,
  snippets,
  registry: readOptionalJson("content-registry.json"),
  problems: (readOptionalJson("problems.json") || []).map(({ id, title, url, platform, status, tags, date }) => ({ id, title, url, platform, status, tags, date })),
  site: readOptionalJson("site.json"),
};
snapshot.contentDigest = sha256(JSON.stringify(snapshot));

// The public asset directory is generated exclusively from the verified pin.
const assetsDestination = path.join(appRoot, "public", "assets");
fs.rmSync(assetsDestination, { recursive: true, force: true });
if (fs.existsSync(path.join(contentRoot, "assets"))) fs.cpSync(path.join(contentRoot, "assets"), assetsDestination, { recursive: true });

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(
  outputPath,
  `// Generated by scripts/generate-content-snapshot.cjs. Do not edit by hand.\nexport const generatedContentSnapshot = ${JSON.stringify(snapshot)} as const;\n`,
  "utf8",
);
console.log(JSON.stringify({ output: outputPath, posts: posts.length, snippets: snippets.length, snapshotDigest: snapshot.snapshotDigest, contentDigest: snapshot.contentDigest }, null, 2));
